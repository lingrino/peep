with open(out, "w") as f:
    f.write(NOTICE)
    f.write("extension Emoji {\n")
    f.write(f"    /// \"name emoji\\n\" for each of the {len(pairs)} shortcodes, sorted by name.\n")
    f.write('    static let table: StaticString = """\n')
    for name, emoji in pairs:
        f.write(f"        {name} {emoji}\n")
    f.write('        """\n}\n')
print(f"{len(pairs)} shortcodes -> {os.path.normpath(out)}")
