#!/usr/bin/env python3
"""Generates Sources/Core/Markdown/EmojiTable.swift: GitHub's emoji shortcodes (`:tada:`).

Input: emojibase-data's en/shortcodes/github.json (npm package `emojibase-data`, MIT), a JSON
object mapping an emoji's code points ("1F389", "1F468-200D-1F469") to its GitHub name or
names. Usage: Scripts/gen-emoji.py path/to/github.json
"""
import json
import os
import sys

src = json.load(open(sys.argv[1]))
pairs = []
for hexcode, names in src.items():
    scalars = [int(h, 16) for h in hexcode.split("-")]
    # A lone code point may default to text presentation (U+2049, U+2764): ask for the emoji
    # form. Harmless for the ones that are emoji by default.
    if len(scalars) == 1:
        scalars.append(0xFE0F)
    emoji = "".join(chr(c) for c in scalars)
    for name in names if isinstance(names, list) else [names]:
        assert all(c in "abcdefghijklmnopqrstuvwxyz0123456789_+-" for c in name), name
        assert len(name) < 64 and len(emoji.encode()) < 64
        pairs.append((name, emoji))
pairs.sort()

